'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
assert(fs.existsSync('view_feedback.js'), 'registered feedback owners must exist');
const F = require('../view_feedback.js');
const changes = [];
const health = F.register('health', state => changes.push(state));
const other = F.register('other', () => {});
const first = health.begin('/health');
assert(F.known(first) && F.current(first));
health.fail(first, 'read_failed');
const original = health.snapshot().error;
assert.equal(original.observations, 1);
const second = health.begin('/health');
health.fail(second, 'read_failed');
assert.equal(health.snapshot().error.identity, original.identity);
assert.equal(health.snapshot().error.observations, 2);
assert.equal(health.snapshot().error.firstObservedAt, original.firstObservedAt);
const unrelated = other.begin('/health');
other.succeed(unrelated);
assert(health.snapshot().error, 'another owner cannot clear failure');
const alternate = health.begin('/elsewhere');
health.succeed(alternate);
const third = health.begin('/health');
assert(health.snapshot().error, 'another query cannot clear the prior query failure');
assert.equal(health.succeed(first), false, 'superseded success cannot recover current display');
assert.equal(health.fail(second, 'read_failed'), false, 'superseded failure cannot publish');
assert.equal(health.succeed(third), true);
assert.equal(health.snapshot().error, null, 'latest accepted same-query success recovers older polling failure');
const a = health.begin('A');
health.begin('B');
const again = health.begin('A');
assert.equal(F.current(a), false, 'A-B-A needs generation, not value equality');
assert.equal(F.current(again), true);
health.invalidate();
assert.equal(F.current(again), false);
assert.equal(F.known({owner:'health', query:'A'}), false, 'plain option objects cannot claim display ownership');
assert.throws(() => F.register('silent'), /renderer/);
assert.equal(F.code({status:422}), 'too_large');
assert.equal(F.code({status:409}), 'conflict');
assert.equal(F.code(new TypeError('PRIVATE-CANARY'), true), 'write_uncertain');
assert(!JSON.stringify(changes).includes('PRIVATE-CANARY'));
console.log('PASS stable feedback identity, current-generation recovery, registered capability and fixed errors');

(async () => {
  const vm = require('node:vm');
  const elements = new Map();
  const doc = {getElementById:id=>elements.get(id), createElement:()=>({textContent:'',setAttribute(){}}),
    body:{prepend(el){elements.set(el.id,el);}}, addEventListener(){}};
  let mode = 'failure';
  const nativeCalls = [];
  const context = {URL, Request, Response, Headers, AbortController, DOMException, setTimeout, clearTimeout,
    document:doc, location:{href:'http://localhost/dns_frontend.html', origin:'http://localhost', pathname:'/dns_frontend.html', replace(){}},
    TraceViewFeedback:F,
    fetch:async (url, options) => {
      if(String(url).endsWith('/auth/me')) return new Response(JSON.stringify({csrf_token:'fixture',user:{role:'admin'}}));
      nativeCalls.push(options);
      return new Response('{}', {status:mode==='good'?200:mode==='denied'?403:503,
        headers:mode==='security'?{'X-TraceDNS-Security-Error':'security_unavailable'}:{}});
    }};
  context.window = context;
  vm.createContext(context);
  vm.runInContext(fs.readFileSync('auth_frontend.js','utf8'), context);
  await context.TraceAuth.ready;
  const owner = F.register('auth-test', () => {});
  const request = owner.begin('health');
  await assert.rejects(context.fetch('/delivery-health', {feedback:request}), e=>e.status===503);
  assert(!elements.get('security-message')?.textContent, 'registered HTTP error is local only');
  assert(!Object.hasOwn(nativeCalls.at(-1), 'feedback'), 'UI capability is never passed to transport');
  await assert.rejects(context.fetch('/unconverted'));
  assert(elements.get('security-message').textContent.includes('503'), 'unconverted requests retain fallback');
  context.TraceAuth.message('');
  await assert.rejects(context.fetch('/spoofed', {feedback:{owner:'auth-test'}}));
  assert(elements.get('security-message').textContent.includes('503'), 'unregistered tokens cannot suppress errors');
  context.TraceAuth.message('');
  mode = 'security';
  await assert.rejects(context.fetch('/settings', {feedback:request}), e=>e.code==='security_unavailable');
  assert(elements.get('security-message').textContent.includes('Security or audit'));
  mode = 'good';
  await context.fetch('/delivery-health', {feedback:request});
  assert(elements.get('security-message').textContent.includes('Security or audit'), 'unrelated success never clears security');
  let invalidated = 0;
  context.TraceAuth.onInvalidated(() => invalidated++);
  mode = 'denied';
  await assert.rejects(context.fetch('/settings', {feedback:request}), e=>e.status===403 && e.code==='forbidden');
  assert.equal(invalidated, 1);
  assert.equal(context.TraceAuth.accessInvalidated,true);
  mode='good';await context.fetch('/unrelated-success');
  assert.equal(context.TraceAuth.accessInvalidated,true,'unrelated success cannot restore revoked UI capabilities');
  assert(elements.get('security-message').textContent.includes('Permission denied'));
  owner.invalidate();
  const count = nativeCalls.length;
  await assert.rejects(context.fetch('/late', {feedback:request}), e=>e.name==='AbortError');
  assert.equal(nativeCalls.length, count, 'obsolete owner cannot dispatch');
  context.TraceViewFeedback = undefined;
  mode = 'failure';
  await assert.rejects(context.fetch('/missing-asset', {feedback:request}));
  assert(elements.get('security-message').textContent.includes('503'), 'missing asset fails visibly');
  console.log('PASS local HTTP opt-in, security fallback, missing asset and obsolete owner');
})().catch(error => { console.error(error); process.exitCode = 1; });
